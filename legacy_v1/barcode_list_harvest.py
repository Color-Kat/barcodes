def ean_valid(code):
    if not code.isdigit() or len(code) not in (8, 12, 13, 14):
        return False
    if code.startswith("0000"):
        return False  # внутренние кассовые коды, не GS1
    digits = [int(c) for c in code]
    check = digits[-1]
    body = digits[:-1][::-1]
    s = sum(d * (3 if i % 2 == 0 else 1) for i, d in enumerate(body))
    return (10 - s % 10) % 10 == check


def main():
    db = sqlite3.connect(DB, timeout=120)
    db.execute("CREATE TABLE IF NOT EXISTS harvest_done (word TEXT PRIMARY KEY)")
    done = {r[0] for r in db.execute("SELECT word FROM harvest_done")}
    total = 0
    sess = requests.Session()
    sess.headers.update(HEADERS)
    for w in WORDS:
        if w in done:
            continue
        try:
            r = sess.get(URL + urllib.parse.quote(w), timeout=60)
            r.raise_for_status()
        except Exception as e:
            print(w, "ERR", e)
            time.sleep(10)
            continue
        rows = re.findall(r'>(\d{6,14})</a></td>\s*<td[^>]*>([^<]+)</td>', r.text)
        if not rows:
            # сайт молча отдаёт пустую выдачу при превышении лимита запросов —
            # слово НЕ помечаем, выходим; продолжить тем же запуском позже
            print(f"{w}: пустая выдача — похоже на rate-limit, стоп. "
                  f"Перезапусти скрипт позже, он продолжит с этого слова.")
            break
        good = [(c, n.strip()) for c, n in rows if ean_valid(c) and len(n.strip()) > 3]
        db.executemany(
            "INSERT OR IGNORE INTO products (barcode, name, source) VALUES (?,?,'barcode-list')",
            good)
        db.execute("INSERT OR IGNORE INTO harvest_done VALUES (?)", (w,))
        db.commit()
        total += len(good)
        print(f"{w}: строк {len(rows)}, валидных {len(good)}, всего {total}")
        time.sleep(PAUSE)
    n = db.execute("SELECT count(*) FROM products WHERE source='barcode-list'").fetchone()[0]
    print("Итого в базе от barcode-list:", n)


if __name__ == "__main__":
    main()
